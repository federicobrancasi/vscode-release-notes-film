// The codicon font's glyphs by name (src/ui/codiconMap.ts), from @vscode/codicons' codicon.csv, and the font itself
// (public/fonts/codicon.ttf): the redrawn VS Code UI uses the product's own icons. Run after updating the package.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const csv = fs.readFileSync(path.join(ROOT, 'node_modules/@vscode/codicons/dist/codicon.csv'), 'utf8').trim().split('\n').slice(1);
const map = Object.fromEntries(csv.map((l) => l.split(',')).map(([name, , hex]) => [name, parseInt(hex, 16)]));
const out = `// Generated by scripts/codicon-map.mjs from @vscode/codicons (codicon.csv): name → code point.\nexport const CODICONS: Record<string, number> = ${JSON.stringify(map)};\n`;
fs.writeFileSync(path.join(ROOT, 'src/ui/codiconMap.ts'), out);
fs.copyFileSync(path.join(ROOT, 'node_modules/@vscode/codicons/dist/codicon.ttf'), path.join(ROOT, 'public/fonts/codicon.ttf'));
console.log(`src/ui/codiconMap.ts: ${Object.keys(map).length} codicons`);
